def add_nums(a,b):
    """returns addition of numbers"""
    return a + b
def divide_nums(a,b):
    """returns division of numbers"""
    return a / b
def subtract_nums(a,b):
    """returns substraction of numbers"""
    return a - b
def power(a,b):
    """returns power of numbers"""
    return a ** b
def multiply_nums(a,b):
    """return multiplication of numbers"""
    return a * b
